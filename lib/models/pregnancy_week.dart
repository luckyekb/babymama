class PregnancyWeek {
  final int weekNumber;
  final String fruitEmoji;
  final String fruitName;
  final String babySize;
  final String babyDevelopment;
  final String bodyChanges;
  final List<String> symptoms;
  final List<String> nutritionTips;
  final List<String> generalTips;

  const PregnancyWeek({
    required this.weekNumber,
    required this.fruitEmoji,
    required this.fruitName,
    required this.babySize,
    required this.babyDevelopment,
    required this.bodyChanges,
    required this.symptoms,
    required this.nutritionTips,
    required this.generalTips,
  });
}
